#!/usr/bin/env python3
"""Extract data blobs from the original default.xbe for the build.

  extract_data.py <default.xbe> <outdir>

Writes C include files with data the source uses but doesn't carry itself
(long text from the original release), so the repository holds no copy:

  credits.inc   the intro's scrolling credits (g_CreditsText, 0x000A2278)
  text.h        the story, cutscene and tutorial text: TEXT_<address> macros
                (wide strings), named by where each string is in default.xbe
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../tools'))
from xbe import Xbe  # noqa: E402

BLOBS = [
    ('credits.inc', 0x000A2278),
]

# The wide strings of the story, the ending's dialogue, the Tutorial and
# the Experiment's help (all in .rdata between these addresses) go to
# text.h; the source uses them as TEXT_<address>.
TEXT_RANGE = (0x0009F000, 0x000A0340)


def wide_strings(x, lo=0x0009EF00, hi=0x000A0600, min_len=4):
    """(address, text) of the 4-aligned UTF-16 strings of at least min_len
    printable characters in [lo, hi)."""
    img = x.flat_image()
    out = []
    va = lo
    while va < hi:
        o = va - x.base
        n = 0
        while img[o + 2 * n + 1] == 0 and 32 <= img[o + 2 * n] < 127:
            n += 1
        if n >= min_len and img[o + 2 * n:o + 2 * n + 2] == b'\0\0':
            out.append((va, img[o:o + 2 * n].decode('utf-16-le')))
            va += (2 * n + 2 + 3) & ~3
        else:
            va += 4
    return out


def c_string(data):
    out, line = [], ''
    for b in data:
        ch = chr(b)
        if ch == '\\' or ch == '"':
            line += '\\' + ch
        elif 32 <= b < 127:
            line += ch
        else:
            line += '\\x%02x""' % b
        if len(line) >= 72:
            out.append('"%s"' % line)
            line = ''
    if line:
        out.append('"%s"' % line)
    return '\n'.join(out) + '\n'


def main():
    x = Xbe(sys.argv[1])
    img = x.flat_image()
    os.makedirs(sys.argv[2], exist_ok=True)
    for name, va in BLOBS:
        data = img[va - x.base:].split(b'\0')[0]
        with open(os.path.join(sys.argv[2], name), 'w') as f:
            f.write('/* Generated by tools/extract_data.py from the original default.xbe (0x%08X). */\n' % va)
            f.write(c_string(data))
    with open(os.path.join(sys.argv[2], 'text.h'), 'w') as f:
        f.write('/* Generated by tools/extract_data.py from the original default.xbe. */\n')
        for va, text in wide_strings(x, TEXT_RANGE[0], TEXT_RANGE[1], 1):
            f.write('#define TEXT_%08X L%s\n' % (va, c_string(text.encode('latin-1')).strip().replace('\n', ' L')))


if __name__ == '__main__':
    main()

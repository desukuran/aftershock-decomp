#!/usr/bin/env python3
"""Type the floating-point constants in .rdata so Ghidra prints their values.

  gen_consts.py            writes symbols/consts.txt

MSVC puts every float/double literal in .rdata. Untyped, Ghidra shows them
as DAT_000b1960; typed in a read-only block, it folds them into the code as
literals. The candidates are the CRT's _real@xxxxxxxx labels from
symbols/xdklib.txt and every .rdata address the game code references in
build/export/decomp. Float or double is decided from the label's hex
digits, or else by which reading gives a "clean" number (a literal someone
typed: few significant digits).
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 0x10000
RDATA = (0x000B0C40, 0x000B6138)
GAME = (0x00011000, 0x0003867D)


def clean(v, digits, cast=float):
    if v != v or v in (float('inf'), float('-inf')):
        return False
    if v == 0:
        return True
    if not 1e-6 <= abs(v) <= 1e8:
        return False
    return cast(float(f'{v:.{digits}g}')) == v


def operand_sizes(img):
    """{address: 'float'|'double'} from how the game code's instructions read
    .rdata (dword ptr / qword ptr). Needs capstone (tools/venv)."""
    try:
        from capstone import Cs, CS_ARCH_X86, CS_MODE_32
    except ImportError:
        return {}
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    out = {}
    code = img[GAME[0] - BASE:GAME[1] - BASE]
    for ins in md.disasm(code, GAME[0]):
        for m in re.finditer(r'(dword|qword) ptr \[0x([0-9a-f]+)\]', ins.op_str):
            a = int(m.group(2), 16)
            if not RDATA[0] <= a < RDATA[1]:
                continue
            if m.group(1) == 'qword':
                out[a] = 'double'
            elif ins.mnemonic.startswith(('f', 'movss', 'addss', 'subss', 'mulss', 'divss', 'comiss', 'ucomiss',
                                          'maxss', 'minss', 'sqrtss', 'cvtss')):
                out.setdefault(a, 'float')
    return out


def main():
    img = open(os.path.join(ROOT, 'build/default.flat'), 'rb').read()
    f32 = lambda a: struct.unpack_from('<f', img, a - BASE)[0]
    f64 = lambda a: struct.unpack_from('<d', img, a - BASE)[0]
    as_f32 = lambda v: struct.unpack('<f', struct.pack('<f', v))[0]

    names = {}
    kinds = {}
    used = operand_sizes(img)
    for line in open(os.path.join(ROOT, 'symbols/xdklib.txt')):
        m = re.match(r'([0-9a-f]{8}) (_real(?:@([0-9a-f]+))?) data', line)
        if m and RDATA[0] <= int(m.group(1), 16) < RDATA[1]:
            a = int(m.group(1), 16)
            names[a] = m.group(2)
            if m.group(3):
                kinds[a] = 'float' if len(m.group(3)) == 8 else 'double'

    # .rdata addresses used by game code (decompiler output of the game range).
    refs = set()
    for path in [os.path.join(ROOT, 'build/export/decomp/text.c')]:
        for part in re.split(r'(?m)^// ==== ', open(path).read())[1:]:
            addr = int(re.match(r'.+? @ ([0-9a-f]+)', part).group(1), 16)
            if not GAME[0] <= addr < GAME[1]:
                continue
            for m in re.finditer(r'_000(b[0-9a-f]{4})\b', part):
                a = int(m.group(1), 16)
                if RDATA[0] <= a < RDATA[1]:
                    refs.add(a)
    refs |= set(names) | set(used)

    out = []
    for a in sorted(refs):
        kind = kinds.get(a) or used.get(a)
        if kind is None:
            fv, dv = f32(a), f64(a)
            if clean(fv, 6, as_f32) and (fv != 0 or a + 4 in refs):
                kind = 'float'
            elif clean(dv, 10):
                kind = 'double'
            elif clean(fv, 7, as_f32) or 1e-6 <= abs(fv) <= 1e8:
                kind = 'float'   # computed values like pi/2 or 1/32767.5
            else:
                continue
        # Unique names (the CRT's are often just "_real"); show.py prints the values.
        name = f'{"flt" if kind == "float" else "dbl"}_{a:08x}'
        out.append(f'{a:08x} {name} data:{kind}')
    with open(os.path.join(ROOT, 'symbols/consts.txt'), 'w') as f:
        f.write('# Generated by tools/gen_consts.py -- do not edit\n')
        f.write('\n'.join(out) + '\n')
    print(f'{len(out)} constants')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Extract data blobs from the original default.xbe for the build.

  extract_data.py <default.xbe> <outdir>

Writes C include files with data the source uses but doesn't carry itself
(long text from the original release), so the repository holds no copy:

  credits.inc   the intro's scrolling credits (g_CreditsText, 0x000A2278)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xbe import Xbe  # noqa: E402

BLOBS = [
    ('credits.inc', 0x000A2278),
]


def c_string(data):
    out, line = [], ''
    for b in data:
        ch = chr(b)
        if ch == '\\' or ch == '"':
            line += '\\' + ch
        elif 32 <= b < 127:
            line += ch
        else:
            line += '\\x%02x""' % b
        if len(line) >= 72:
            out.append('"%s"' % line)
            line = ''
    if line:
        out.append('"%s"' % line)
    return '\n'.join(out) + '\n'


def main():
    x = Xbe(sys.argv[1])
    img = x.flat_image()
    os.makedirs(sys.argv[2], exist_ok=True)
    for name, va in BLOBS:
        data = img[va - x.base:].split(b'\0')[0]
        with open(os.path.join(sys.argv[2], name), 'w') as f:
            f.write('/* Generated by tools/extract_data.py from the original default.xbe (0x%08X). */\n' % va)
            f.write(c_string(data))


if __name__ == '__main__':
    main()
